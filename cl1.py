import random, numpy as np

wins=[[0,1,2],[3,4,5],[6,7,8],[0,3,6],[1,4,7],[2,5,8],[0,4,8],[2,4,6]]
Q={}
alpha,gamma,epsilon=.1,.9,1
episodes=50000

def won(b,p):
    return any(all(b[i]==p for i in x) for x in wins)

def act(s,a,e):
    if random.random()<e:return random.choice(a)
    m=max(Q.get((s,x),0) for x in a)
    return random.choice([x for x in a if Q.get((s,x),0)==m])

for ep in range(episodes):
    b=[0]*9
    done=False

    while not done:
        s=tuple(b)
        a=[i for i in range(9) if b[i]==0]
        x=act(s,a,epsilon)
        b[x]=1

        if won(b,1):
            Q[s,x]=Q.get((s,x),0)+alpha*(1-Q.get((s,x),0))
            break

        a=[i for i in range(9) if b[i]==0]
        if not a:
            Q[s,x]=Q.get((s,x),0)+alpha*(.5-Q.get((s,x),0))
            break

        b[random.choice(a)]=-1

        if won(b,-1):
            Q[s,x]=Q.get((s,x),0)+alpha*(-1-Q.get((s,x),0))
            break

        ns=tuple(b)
        na=[i for i in range(9) if b[i]==0]
        target=gamma*max((Q.get((ns,y),0) for y in na),default=0)
        Q[s,x]=Q.get((s,x),0)+alpha*(target-Q.get((s,x),0))

    epsilon=max(.01,np.exp(-.0001*ep))

w=d=l=0

for _ in range(1000):
    b=[0]*9

    while True:
        s=tuple(b)
        a=[i for i in range(9) if b[i]==0]
        x=act(s,a,0)
        b[x]=1

        if won(b,1):
            w+=1
            break

        a=[i for i in range(9) if b[i]==0]
        if not a:
            d+=1
            break

        b[random.choice(a)]=-1

        if won(b,-1):
            l+=1
            break

        if not any(i==0 for i in b):
            d+=1
            break

print(f"Wins: {w} ({w/1000:.1%})")
print(f"Draws: {d} ({d/1000:.1%})")
print(f"Losses: {l} ({l/1000:.1%})")

