from qiskit import QuantumCircuit
from qiskit_aer import AerSimulator

# Initial and goal states
initial = [1, 2, 0, 3]
goal = [1, 2, 3, 0]

# Create circuit with 2 qubits
qc = QuantumCircuit(2, 2)

# Step 1: Create superposition
qc.h(0)
qc.h(1)

# Step 2: Oracle marks |11> (Right)
qc.cz(0, 1)

# Step 3: Grover diffusion
qc.h([0, 1])
qc.x([0, 1])
qc.cz(0, 1)
qc.x([0, 1])
qc.h([0, 1])

# Step 4: Measure
qc.measure([0, 1], [0, 1])

# Step 5: Run simulator
sim = AerSimulator()
result = sim.run(qc, shots=100).result()
counts = result.get_counts()

# Step 6: Find selected move
answer = max(counts, key=counts.get)
moves = {"00": "Up", "01": "Down",
         "10": "Left", "11": "Right"}

print("Initial:", initial)
print("Quantum result:", counts)
print("Selected move:", moves[answer])

# Apply the selected move to this puzzle
if answer == "11":
    initial[2], initial[3] = initial[3], initial[2]

print("Final:", initial)
print("Goal reached:", initial == goal)

