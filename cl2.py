import pandas as pd
import kagglehub
import networkx as nx
import matplotlib.pyplot as plt
from pgmpy.models import DiscreteBayesianNetwork
from pgmpy.inference import VariableElimination

# Load dataset
path = kagglehub.dataset_download("cherngs/heart-disease-cleveland-uci")
data = pd.read_csv(path + "/heart_cleveland_upload.csv")
data.rename(columns={"condition": "disease"}, inplace=True)
data = data.replace("?", float("nan")).dropna()

print("Sample Data:\n", data.head())
print("\nAttributes and Datatypes:\n", data.dtypes)

# Convert continuous values into categories
for col in ["age", "trestbps", "chol", "thalach", "oldpeak"]:
    data[col] = pd.cut(data[col], bins=3, labels=False)

# Create Bayesian Network (matching image)
edges = [("disease", col) for col in data.columns if col != "disease"]
model = DiscreteBayesianNetwork(edges)
plt.figure(figsize=(12, 8))
G = nx.DiGraph(model.edges())
pos = nx.spring_layout(G, seed=42)

nx.draw(G, pos, with_labels=True,
        node_color="lightblue", node_size=2200,
        font_size=9, font_weight="bold",
        arrows=True, arrowsize=20)

plt.title("Bayesian Network for Heart Disease Prediction")
plt.show()

# Learn CPDs
model.fit(data)
print("\nCPDs learned successfully")

# Perform inference
infer = VariableElimination(model)

print("\n1. Probability of Disease given restecg=1")
print(infer.query(["disease"], evidence={"restecg": 1}))

print("\n2. Probability of Disease given cp=2")
print(infer.query(["disease"], evidence={"cp": 2}))

